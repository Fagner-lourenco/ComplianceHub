for (const [bad, good] of replacements) {
  const regex = new RegExp(bad.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
  const matches = content.match(regex);
  if (matches) {
    totalChanges += matches.length;
    content = content.replace(regex, good);
  }
}

